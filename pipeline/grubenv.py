#!/usr/bin/env python3
"""Read and write the GRUB environment block (EFI/ubuntu/grubenv).

A GRUB environment block is exactly 1024 bytes: two header lines, then
newline-terminated key=value lines, with the rest padded by '#'.  GRUB's
save_env writes this format, and grub-editenv is the usual editor.  The
minimal recovery image does not ship grub-common, so this module gives the
build scripts (and a recovery shell with python3) the same operation
without grub-editenv.

Usage:
    grubenv.py show FILE
    grubenv.py set FILE KEY VALUE
    grubenv.py unset FILE KEY
    grubenv.py create FILE

`set` and `unset` preserve the other keys.  A missing file starts empty.
"""
from __future__ import annotations

import os
import re
import sys

SIZE = 1024
HEADER = (
    b"# GRUB Environment Block\n"
    b"# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"
)
KEY_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


class GrubenvError(ValueError):
    pass


def read(path: str) -> dict[str, str]:
    """Return the key=value lines of *path*; a missing file is empty."""
    try:
        with open(path, "rb") as f:
            data = f.read()
    except FileNotFoundError:
        return {}
    except OSError as exc:
        raise GrubenvError(f"cannot read {path}: {exc}") from exc
    if len(data) != SIZE:
        raise GrubenvError(
            f"{path} is {len(data)} bytes, not the expected {SIZE}")
    values: dict[str, str] = {}
    for raw in data.split(b"\n"):
        if not raw or raw.startswith(b"#") or b"=" not in raw:
            continue
        key, value = raw.split(b"=", 1)
        try:
            values[key.decode("ascii")] = value.decode("ascii")
        except UnicodeDecodeError as exc:
            raise GrubenvError(f"{path} contains a non-ASCII line") from exc
    return values


def write(path: str, values: dict[str, str]) -> None:
    """Write *values* in the 1024-byte format GRUB expects."""
    body = bytearray()
    for key, value in values.items():
        if not KEY_RE.fullmatch(key):
            raise GrubenvError(f"invalid grubenv key: {key!r}")
        if "\n" in value or "\r" in value:
            raise GrubenvError(f"grubenv value for {key} contains a newline")
        try:
            line = f"{key}={value}\n".encode("ascii")
        except UnicodeEncodeError as exc:
            raise GrubenvError(f"grubenv value for {key} is not ASCII") from exc
        body += line
    room = SIZE - len(HEADER)
    if len(body) > room:
        raise GrubenvError(f"grubenv is full ({len(body)} > {room} bytes)")
    data = HEADER + bytes(body) + b"#" * (room - len(body))
    assert len(data) == SIZE
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    os.chmod(path, 0o644)


def set_key(path: str, key: str, value: str) -> dict[str, str]:
    values = read(path)
    values[key] = value
    write(path, values)
    return values


def unset_key(path: str, key: str) -> dict[str, str]:
    values = read(path)
    values.pop(key, None)
    write(path, values)
    return values


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    command, path = argv[1], argv[2]
    try:
        if command == "show" and len(argv) == 3:
            values = read(path)
            for key, value in values.items():
                print(f"{key}={value}")
            return 0
        if command == "create" and len(argv) == 3:
            write(path, {})
            return 0
        if command == "set" and len(argv) == 5:
            set_key(path, argv[3], argv[4])
            return 0
        if command == "unset" and len(argv) == 4:
            unset_key(path, argv[3])
            return 0
    except (GrubenvError, OSError) as exc:
        print(f"grubenv: {exc}", file=sys.stderr)
        return 1
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
